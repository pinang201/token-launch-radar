// Launch Radar page logic: renders window.RADAR (written by main.ts beside this page) as a sortable,
// filterable board with a per-protocol detail drawer. No fetch, no imports, no network: the data
// script is the only input, and every control re-renders from it in place.
'use strict';

const R = window.RADAR;
const rows = R.rows;
const bySlug = new Map(rows.map((r) => [r.slug, r]));

const state = { q: '', cat: '', chain: '', watch: false, sort: 'implied_value_usd', dir: -1 };

const $ = (id) => document.getElementById(id);
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

/** Dollars, compact at scale: $842, $96.4K, $12.8M, $2.76B. */
function money(n) {
  if (n === null || n === undefined) return '—';
  const a = Math.abs(n);
  if (a >= 1e9) return `$${(n / 1e9).toFixed(2)}B`;
  if (a >= 1e6) return `$${(n / 1e6).toFixed(1)}M`;
  if (a >= 1e3) return `$${(n / 1e3).toFixed(1)}K`;
  return `$${Math.round(n)}`;
}
/** Dollars in full, with separators, for the detail view. */
function moneyFull(n) {
  return `$${Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ',')}`;
}
function pct(n) {
  if (n === null || n === undefined) return '<span class="muted">—</span>';
  const cls = n > 0 ? 'up' : n < 0 ? 'down' : '';
  return `<span class="${cls}">${n > 0 ? '+' : ''}${n.toFixed(1)}%</span>`;
}
function ageText(days) {
  if (days === null || days === undefined) return '—';
  if (days < 365) return `${days}d`;
  return `${(days / 365).toFixed(1)}y`;
}

// ---------------------------------------------------------------- masthead, stats, peers
$('m-asof').textContent = R.as_of;
$('m-model').textContent = R.model_version;
$('m-floor').textContent = money(R.floor_usd);
$('source-line').textContent = `Source: ${R.source} · ${R.counts.protocols} protocols scanned · board generated by the entry program from the sealed snapshot alone.`;

$('stats').innerHTML = [
  [R.counts.protocols, 'protocols scanned', ''],
  [R.counts.trading, 'already trading — set apart', ''],
  [R.counts.board, 'pre-token protocols ranked', 'hot'],
  [R.counts.watchlist, 'watchlist covered in full', 'amber'],
  [R.counts.below_floor, 'found below the floor', 'hot'],
].map(([v, label, cls]) => `<div class="stat ${cls}"><b>${v}</b><span>${label}</span></div>`).join('');

$('peer-line').innerHTML =
  `<span>Peer multiples by category (median, trading peers):</span>` +
  R.peers.slice(0, 8).map((g) => `<span><b>${esc(g.category)}</b> ${g.median_multiple.toFixed(2)}× · ${g.peers} peers</span>`).join('') +
  `<span><b>Market-wide</b> ${R.global_multiple.toFixed(2)}×</span>`;

// ---------------------------------------------------------------- filters
const cats = [...new Set(rows.map((r) => r.category).filter(Boolean))].sort();
$('f-cat').innerHTML += cats.map((c) => `<option>${esc(c)}</option>`).join('');
const chains = [...new Set(rows.flatMap((r) => r.chains))].sort();
$('f-chain').innerHTML += chains.map((c) => `<option>${esc(c)}</option>`).join('');

function visible() {
  const q = state.q.trim().toLowerCase();
  return rows.filter((r) =>
    (state.cat === '' || r.category === state.cat) &&
    (state.chain === '' || r.chains.includes(state.chain)) &&
    (!state.watch || r.watchlist) &&
    (q === '' || r.name.toLowerCase().includes(q) || r.slug.includes(q)));
}

const SORTS = {
  rank: (r) => r.rank,
  name: (r) => r.name.toLowerCase(),
  category: (r) => (r.category ?? '').toLowerCase(),
  tvl_usd: (r) => r.tvl_usd,
  change_7d: (r) => r.change_7d ?? -Infinity,
  age_days: (r) => r.age_days ?? -1,
  peer: (r) => r.model.peer_multiple,
  implied_value_usd: (r) => r.implied_value_usd,
};

function render() {
  const list = visible().sort((a, b) => {
    const f = SORTS[state.sort];
    const d = f(a) < f(b) ? -1 : f(a) > f(b) ? 1 : a.rank - b.rank;
    return d * state.dir;
  });
  $('count').textContent = `Showing ${list.length} of ${rows.length} ranked protocols`;
  $('empty').hidden = list.length > 0;
  $('rows').innerHTML = list.map((r) => `
    <tr data-slug="${esc(r.slug)}">
      <td class="num rank">${r.rank}</td>
      <td class="name">${r.watchlist ? '<span class="wd" title="On the house watchlist">◆</span>' : ''}${esc(r.name)}<span class="slug">${esc(r.slug)}</span></td>
      <td class="cat">${esc(r.category ?? '—')}</td>
      <td class="chains">${esc(r.chains.slice(0, 3).join(', '))}${r.chains.length > 3 ? ` +${r.chains.length - 3}` : ''}</td>
      <td class="num money">${money(r.tvl_usd)}</td>
      <td class="num">${pct(r.change_7d)}</td>
      <td class="num">${ageText(r.age_days)}</td>
      <td class="num money">${r.model.peer_multiple.toFixed(2)}×</td>
      <td class="num implied">${money(r.implied_value_usd)}</td>
    </tr>`).join('');
  document.querySelectorAll('#rows tr').forEach((tr) =>
    tr.addEventListener('click', () => openDetail(tr.dataset.slug)));
  document.querySelectorAll('th.sortable').forEach((th) => {
    const on = th.dataset.sort === state.sort;
    th.classList.toggle('sorted', on);
    th.classList.toggle('asc', on && state.dir === 1);
  });
}

document.querySelectorAll('th.sortable').forEach((th) =>
  th.addEventListener('click', () => {
    const key = th.dataset.sort;
    if (state.sort === key) state.dir = -state.dir;
    else { state.sort = key; state.dir = key === 'name' || key === 'category' ? 1 : -1; }
    render();
  }));
$('f-q').addEventListener('input', (e) => { state.q = e.target.value; render(); });
$('f-cat').addEventListener('change', (e) => { state.cat = e.target.value; render(); });
$('f-chain').addEventListener('change', (e) => { state.chain = e.target.value; render(); });
$('f-watch').addEventListener('change', (e) => { state.watch = e.target.checked; render(); });

// ---------------------------------------------------------------- detail drawer
function factorRow(label, value, scale, note) {
  const w = Math.max(3, Math.min(100, (value / scale) * 100));
  return `<div class="factor"><span>${label}</span><span class="bar"><i style="width:${w}%"></i></span><span class="fv">${value.toFixed(2)}×</span></div>${note ? `<p class="factor-note">${note}</p>` : ''}`;
}

function openDetail(slug) {
  const r = bySlug.get(slug);
  if (!r) return;
  const m = r.model;
  $('drawer-body').innerHTML = `
    <h2>${r.watchlist ? '<span class="wd">◆</span> ' : ''}${esc(r.name)}</h2>
    <div class="d-slug">${esc(r.slug)} · listed on DefiLlama ${esc(r.listed_at ?? 'date unrecorded')}</div>
    <div class="badges">
      <span class="badge pre">pre-token</span>
      ${r.watchlist ? '<span class="badge watch">house watchlist</span>' : '<span class="badge">below the watchlist floor</span>'}
      <span class="badge">${esc(r.category ?? 'uncategorised')}</span>
      <span class="badge">rank #${r.rank} of ${rows.length}</span>
    </div>
    <div class="d-stats">
      <div class="d-stat"><span>Implied launch value</span><b class="big">${moneyFull(r.implied_value_usd)}</b></div>
      <div class="d-stat"><span>TVL</span><b>${moneyFull(r.tvl_usd)}</b></div>
      <div class="d-stat"><span>7-day TVL change</span><b>${r.change_7d === null ? '—' : `${r.change_7d > 0 ? '+' : ''}${r.change_7d.toFixed(1)}%`}</b></div>
      <div class="d-stat"><span>Running tokenless</span><b>${r.age_days === null ? 'unrecorded' : `${r.age_days} days`}</b></div>
    </div>
    <h3>How the value is built</h3>
    ${factorRow('Peer multiple', m.peer_multiple, 3, `Median market-cap / TVL of trading ${esc(r.category ?? '')} peers, blended with its main chain's and shrunk toward the market-wide ${R.global_multiple.toFixed(2)}×; ${m.category_peers} trading peer${m.category_peers === 1 ? '' : 's'} in its category.`)}
    ${factorRow('Growth factor', m.growth_factor, 1.6, 'From its 7-day TVL change, clamped so one wild week cannot dominate.')}
    ${factorRow('Maturity factor', m.maturity_factor, 1.2, 'From how long it has run with no token, capped at five years.')}
    <p class="factor-note">${moneyFull(r.tvl_usd)} TVL × ${m.peer_multiple.toFixed(2)} × ${m.growth_factor.toFixed(2)} × ${m.maturity_factor.toFixed(2)} = <b>${moneyFull(r.implied_value_usd)}</b> implied, if it launched at its peers' pricing on this record.</p>
    <h3>Chains</h3>
    <p>${esc(r.chains.join(', ') || '—')}</p>
    <h3>Farm plan — ${r.farm_steps.length} steps</h3>
    <ol class="farm">${r.farm_steps.map((s) => `<li>${esc(s)}</li>`).join('')}</ol>`;
  $('drawer').hidden = false;
  $('scrim').hidden = false;
}
function closeDetail() { $('drawer').hidden = true; $('scrim').hidden = true; }
$('drawer-x').addEventListener('click', closeDetail);
$('scrim').addEventListener('click', closeDetail);
document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeDetail(); });

// ---------------------------------------------------------------- trading strip
$('trading').innerHTML = R.trading.map((t) => `
  <span class="chip"><b>${esc(t.name)}</b>${t.symbol ? ` <span class="sym">${esc(t.symbol)}</span>` : ''} · mcap ${money(t.mcap_usd)} · ${t.multiple.toFixed(2)}× TVL</span>`).join('');

render();
